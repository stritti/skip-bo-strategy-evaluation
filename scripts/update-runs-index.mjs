/**
 * Regenerates the shared-run data artifacts:
 *  - public/data/runs/index.json with precomputed aggregates per run
 *  - src/generated/runsIndex.ts (typed copy for synchronous SSG rendering of /runs/:seed)
 *  - public/sitemap.xml (all de/en routes + one permalink per shared run)
 *
 * Usage: npm run runs:index
 */
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { normalizeSharedRun } from '../src/services/sharedRuns.ts';

const runsDir = fileURLToPath(new URL('../public/data/runs/', import.meta.url));
const indexPath = join(runsDir, 'index.json');
const SITE_URL = 'https://skip-bo-strategy-analysis.netlify.app';

const previous = JSON.parse(readFileSync(indexPath, 'utf-8'));
const previousByFile = new Map(previous.map(e => [e.file, e]));

const files = readdirSync(runsDir).filter(f => f.endsWith('.json') && f !== 'index.json').sort();

const entries = files.map(file => {
    const run = normalizeSharedRun(JSON.parse(readFileSync(join(runsDir, file), 'utf-8')), { file });
    if (!run) throw new Error(`cannot normalize ${file}`);
    const old = previousByFile.get(file) ?? {};
    return {
        file,
        label: old.label ?? file,
        strategyP1: run.strategyP1,
        strategyP2: run.strategyP2,
        gamesCount: run.gamesCount,
        winsP1: run.winsP1,
        winsP2: run.winsP2,
        ties: run.ties ?? 0,
        totalTurns: run.totalTurns,
        totalJokers: run.totalJokers,
        seed: run.seed,
        timestamp: run.timestamp
    };
});

writeFileSync(indexPath, JSON.stringify(entries, null, 2) + '\n');

const generatedDir = fileURLToPath(new URL('../src/generated/', import.meta.url));
mkdirSync(generatedDir, { recursive: true });
writeFileSync(
    join(generatedDir, 'runsIndex.ts'),
    '// Generated by scripts/update-runs-index.mjs (npm run runs:index) — do not edit manually.\n' +
    "import type { SharedRunIndexEntry } from '../services/sharedRuns';\n\n" +
    `export const runsIndex: SharedRunIndexEntry[] = ${JSON.stringify(entries, null, 2)};\n`
);

const baseRoutes = [
    ['/', 'weekly', '1.0'],
    ['/analysis', 'weekly', '0.9'],
    ['/strategy', 'weekly', '0.9'],
    ['/validation', 'monthly', '0.8'],
    ['/rules', 'monthly', '0.8'],
    ['/data', 'weekly', '0.7'],
    ['/about', 'monthly', '0.5'],
    ['/runs/:runId', 'monthly', '0.6']
];

const lastmod = new Date().toISOString().slice(0, 10);

const urls = [];
for (const [path, changefreq, priority] of baseRoutes) {
    const concrete = path.includes(':runId')
        ? entries.flatMap(e => [`/runs/${e.file.replace(/\.json$/, '')}`, `/en/runs/${e.file.replace(/\.json$/, '')}`])
        : [path, path === '/' ? '/en' : `/en${path}`];
    for (const loc of concrete) {
        const de = loc.startsWith('/en') ? loc.slice(3) || '/' : loc;
        const en = loc.startsWith('/en') ? loc : (de === '/' ? '/en' : `/en${de}`);
        urls.push(`  <url>
    <loc>${SITE_URL}${loc}</loc>
    <xhtml:link rel="alternate" hreflang="de" href="${SITE_URL}${de}"/>
    <xhtml:link rel="alternate" hreflang="en" href="${SITE_URL}${en}"/>
    <xhtml:link rel="alternate" hreflang="x-default" href="${SITE_URL}${de}"/>
    <lastmod>${lastmod}</lastmod>
    <changefreq>${changefreq}</changefreq>
    <priority>${priority}</priority>
  </url>`);
    }
}

writeFileSync(
    fileURLToPath(new URL('../public/sitemap.xml', import.meta.url)),
    '<?xml version="1.0" encoding="UTF-8"?>\n' +
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"\n' +
    '        xmlns:xhtml="http://www.w3.org/1999/xhtml">\n' +
    urls.join('\n') + '\n</urlset>\n'
);

console.log(`index.json + runsIndex.ts + sitemap.xml updated: ${entries.length} run(s), ${urls.length} sitemap URLs`);
for (const e of entries) {
    console.log(`  ${e.file}: N=${e.gamesCount} wins=${e.winsP1}/${e.winsP2} ties=${e.ties} seed=${e.seed}`);
}
